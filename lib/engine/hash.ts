// Small deterministic hash (two FNV-1a passes -> 16 hex chars). Stands in for
// SHA-256 in the prototype so the audit hash chain can be verified in-browser.
export function hash16(input: string): string {
  let h1 = 0x811c9dc5;
  let h2 = 0x01000193 ^ 0x5bd1e995;
  for (let i = 0; i < input.length; i++) {
    const c = input.charCodeAt(i);
    h1 ^= c;
    h1 = Math.imul(h1, 0x01000193) >>> 0;
    h2 ^= c + i;
    h2 = Math.imul(h2, 0x01000193) >>> 0;
  }
  return h1.toString(16).padStart(8, "0") + h2.toString(16).padStart(8, "0");
}

export function sha256Like(seed: string): string {
  let out = "";
  for (let i = 0; out.length < 64; i++) out += hash16(`${seed}:${i}`);
  return out.slice(0, 64);
}

/** Seeded PRNG (mulberry32) for deterministic demo data. */
export function rng(seed: number) {
  let a = seed >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) >>> 0;
    let t = a;
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}
