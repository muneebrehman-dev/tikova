function defaultHistory(d: Seed) {
  const order: Stage[] = ["intake", "screening", "underwriting", "term_sheet", "committee", "approved"];
  const idx = order.indexOf(d.stage);
  if (idx <= 0) {
    return [
      { id: `${d.id}-h0`, at: d.createdAt, by: "capital_markets" as const, from: null, to: "intake" as Stage, reason: "Deal created" },
      ...(d.stage === "declined" || d.stage === "dead"
        ? [{ id: `${d.id}-hx`, at: d.stageEnteredAt, by: "capital_markets" as const, from: "screening" as Stage, to: d.stage, reason: d.closeReason ?? "Closed" }]
        : []),
    ];
  }
  const start = new Date(d.createdAt).getTime();
  const end = new Date(d.stageEnteredAt).getTime();
  return order.slice(0, idx + 1).map((s, i) => ({
    id: `${d.id}-h${i}`,
    at: new Date(start + ((end - start) * i) / Math.max(idx, 1)).toISOString(),
    by: (i === 0 ? "capital_markets" : d.owner) as Deal["owner"],
    from: i === 0 ? null : order[i - 1],
    to: s,
    reason: i === 0 ? "Deal created" : s === "approved" ? "Approved by credit committee (3–0)" : `Advanced to ${STAGE_LABEL[s]}`,
  }));
}

export const DEALS: Deal[] = seeds.map((d) => ({
  ...d,
  notes: d.notes ?? [],
  history: d.history ?? defaultHistory(d),
}));
