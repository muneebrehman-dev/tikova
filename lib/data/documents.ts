// Lightweight document lists for the other deals (status only).
const GENERIC: DocClass[] = ["rent_roll", "t12", "budget", "appraisal", "pfs"];
const CONSTRUCTION: DocClass[] = ["budget", "appraisal", "pfs", "esa"];

function genericDocs(): DealDocument[] {
  const out: DealDocument[] = [];
  for (const d of DEALS) {
    if (d.id === "harborview") continue;
    const classes = d.productType === "Ground-Up Construction" ? CONSTRUCTION : GENERIC;
    const list = classes.slice(0, Math.max(d.docsTotal, 1));
    list.forEach((c, i) => {
      const status: DealDocument["status"] =
        i < d.docsApproved ? "approved" : i < d.docsApproved + Math.min(d.openFlags, 1) ? "needs_review" : d.stage === "intake" ? "missing" : "ready";
      const name = `${d.name.replace(/[^A-Za-z]/g, "")}_${DOC_CLASS_LABEL[c].split(" ")[0]}.pdf`;
      out.push({
        id: `${d.id}-${c}`,
        dealId: d.id,
        docClass: c,
        title: DOC_CLASS_LABEL[c],
        fileName: status === "missing" ? "—" : name,
        format: "pdf",
        pages: status === "missing" ? 0 : c === "appraisal" ? 118 : 4,
        sizeKb: status === "missing" ? 0 : 420 + i * 133,
        sha256: status === "missing" ? "" : sha256Like(name),
        uploadedAt: d.createdAt,
        uploadedBy: d.owner,
        version: status === "missing" ? 0 : 1,
        status,
        extractable: status !== "missing",
        fields: [],
        validations: [],
      });
    });
  }
  return out;
}

